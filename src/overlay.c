static const uint8_t *glyph_for(char c)
{
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');
    if (c < GLYPH_FIRST || c > GLYPH_LAST)
        return glyphs[0]; /* blank */
    return glyphs[c - GLYPH_FIRST];
}

int overlay_text_width(const char *text, int scale)
{
    if (!text || scale < 1)
        return 0;
    int len = (int)strlen(text);
    if (len == 0)
        return 0;
    /* One column of spacing between glyphs, none after the last. */
    return len * (OVERLAY_GLYPH_W + 1) * scale - scale;
}

void overlay_panel(uint32_t *pixels, int width, int height,
                   int x, int y, int w, int h, uint32_t color, int alpha)
{
    if (alpha < 0) alpha = 0;
    if (alpha > 255) alpha = 255;
    int inv = 255 - alpha;

    int x0 = x < 0 ? 0 : x;
    int y0 = y < 0 ? 0 : y;
    int x1 = x + w > width ? width : x + w;
    int y1 = y + h > height ? height : y + h;

    int sr = (int)((color >> 16) & 0xFF);
    int sg = (int)((color >> 8) & 0xFF);
    int sb = (int)(color & 0xFF);

    for (int py = y0; py < y1; py++) {
        for (int px = x0; px < x1; px++) {
            uint32_t dst = pixels[(size_t)py * width + px];
            int r = ((int)((dst >> 16) & 0xFF) * inv + sr * alpha) / 255;
            int g = ((int)((dst >> 8) & 0xFF) * inv + sg * alpha) / 255;
            int b = ((int)(dst & 0xFF) * inv + sb * alpha) / 255;
            pixels[(size_t)py * width + px] =
                ((uint32_t)r << 16) | ((uint32_t)g << 8) | (uint32_t)b;
        }
    }
}

void overlay_text(uint32_t *pixels, int width, int height,
                  int x, int y, int scale, uint32_t color, const char *text)
{
    if (!pixels || !text || scale < 1)
        return;

    int pen_x = x;
    for (const char *c = text; *c; c++) {
        const uint8_t *glyph = glyph_for(*c);

        for (int row = 0; row < OVERLAY_GLYPH_H; row++) {
            uint8_t bits = glyph[row];
            for (int col = 0; col < OVERLAY_GLYPH_W; col++) {
                if (!(bits & (1u << (OVERLAY_GLYPH_W - 1 - col))))
                    continue;

                /* Each font pixel becomes a scale x scale block. */
                for (int dy = 0; dy < scale; dy++) {
                    int py = y + row * scale + dy;
                    if (py < 0 || py >= height)
                        continue;
                    for (int dx = 0; dx < scale; dx++) {
                        int px = pen_x + col * scale + dx;
                        if (px < 0 || px >= width)
                            continue;
                        pixels[(size_t)py * width + px] = color;
                    }
                }
            }
        }
        pen_x += (OVERLAY_GLYPH_W + 1) * scale;
    }
}
